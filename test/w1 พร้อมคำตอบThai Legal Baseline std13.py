# h. entity ประเภทใดพบบ่อยที่สุดใน class 0 และ class 1
# - Class 0 (ละเมิดสิทธิบัตร): พบ Entity ประเภท 'IP_TYPE' (value: PATENT) และ 'ACTION' (value: INFRINGEMENT)
# - Class 1 (ละเมิดลิขสิทธิ์): พบ Entity ประเภท 'IP_TYPE' (value: COPYRIGHT) และ 'ACTION' (value: INFRINGEMENT)
# - เหตุผล: ทั้งสองกลุ่มเป็นคดีทรัพย์สินทางปัญญา จึงมี Action การละเมิดเหมือนกัน แต่จะแตกต่างกันชัดเจนที่ชนิดของทรัพย์สิน (IP_TYPE)

# i. Physics Gate Weight เฉลี่ยของ class 0 สูงกว่า class 2 หรือไม่ และการนำไปใช้สั่ง IoT
# - สูงกว่า: เพราะประโยค Class 0 มักประกอบด้วยคีย์เวิร์ดทั้ง "สิทธิบัตร" (+2.0) และ "ละเมิด" (+1.5) ทำให้คะแนนเฉลี่ยทะลุเกณฑ์เตือนภัย (เช่น 8.5) 
#   ส่วน Class 2 มักไม่มีคำแสดงการละเมิด คะแนนจึงต่ำกว่า
# - การสั่ง IoT: ในระบบวิจัย สามารถนำค่า weight นี้ไปผูกกับเงื่อนไข (เช่น weight >= 7) เพื่อส่งสัญญาณ (API) 
#   ไปสั่งให้อุปกรณ์ IoT เช่น เปิดไฟแจ้งเตือนความเสี่ยง (Alarm) หรือล็อคระบบความปลอดภัยอัตโนมัติ

# j. Context-aware Confidence Scoring ทำงานอย่างไร พร้อมตัวอย่าง
# - การทำงาน: ระบบไม่ได้ดูแค่คีย์เวิร์ดเดี่ยวๆ แบบ Rule-base แต่จะดู "คำบริบทแวดล้อม" (Context Signal) ที่เป็นคำศัพท์ทางกฎหมายรอบๆ 
#   เพื่อเพิ่มน้ำหนักความมั่นใจ (Confidence Score) ให้กับ Entity นั้นๆ
# - ตัวอย่างประโยค: "จำเลยผลิตสินค้าที่เลียนแบบสิทธิบัตรการประดิษฐ์เลขที่ 12345"
# - อธิบาย: การมีคำว่า "จำเลย", "เลียนแบบ", และ "การประดิษฐ์เลขที่..." เป็นสัญญาณแวดล้อมที่ยืนยันว่านี่คือการพูดถึงการละเมิดสิทธิบัตรจริงๆ 
#   ทำให้ค่า Confidence ของ Entity INFRINGEMENT และ PATENT ในประโยคนี้พุ่งสูงขึ้นเข้าใกล้ 1.0